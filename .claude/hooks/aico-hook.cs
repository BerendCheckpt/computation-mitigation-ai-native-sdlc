// Claude Code hooks for the deterministic layer (.NET 10 file-based app; compiled once, then cached).
//   dotnet run .claude/hooks/aico-hook.cs -- <match|protect-paths|no-secrets|plan-scope|format>
// Reads the hook event JSON from stdin. Hooks are small, concrete and explain every block.
using System.Diagnostics;
using System.Text.Json;
using System.Text.Json.Nodes;
using System.Text.RegularExpressions;
using Cnu.AICO.Core.Generation;
using Cnu.AICO.Core.Matching;
using Cnu.AICO.Core.Specs;

var command = args.FirstOrDefault() ?? "";
var input = JsonNode.Parse(Console.In.ReadToEnd()) ?? new JsonObject();
var cwd = input["cwd"]?.GetValue<string>() ?? Directory.GetCurrentDirectory();
var toolInput = input["tool_input"] as JsonObject ?? new JsonObject();
var filePath = toolInput["file_path"]?.GetValue<string>();
var relPath = filePath is null ? null : Path.GetRelativePath(cwd, Path.GetFullPath(filePath, cwd)).Replace('\\', '/');

return command switch
{
    "match" => Match(),
    "protect-paths" => ProtectPaths(),
    "no-secrets" => NoSecrets(),
    "plan-scope" => PlanScope(),
    "format" => Format(),
    _ => Fail($"unknown hook command '{command}'"),
};

// UserPromptSubmit: deterministic-first. On a confident match, tell the session to call the template tool
// instead of writing code (≈50 tokens instead of thousands). Never blocks the prompt.
int Match()
{
    var prompt = input["prompt"]?.GetValue<string>() ?? "";
    var templates = Path.Combine(cwd, "templates");
    if (prompt.Length == 0 || !Directory.Exists(templates))
        return 0;

    var m = new TemplateMatcher(TemplateRegistry.Load(templates)).Match(prompt);
    if (!m.IsDeterministic)
        return 0;

    var args = string.Join(", ", m.Parameters.Select(kv => $"{kv.Key}=\"{kv.Value}\""));
    return Emit("UserPromptSubmit", new JsonObject
    {
        ["additionalContext"] =
            $"[cnu-aico] Crystallized template '{m.TemplateId}' fully covers this request (confidence {m.Confidence.ToString("0.00", System.Globalization.CultureInfo.InvariantCulture)}). " +
            $"Call the MCP tool {m.ToolName} with {args} instead of writing this code by hand. " +
            "If the user asked for something the template does not cover, say so and implement only the difference.",
    });
}

// PreToolUse(Edit|Write|MultiEdit): block edits to protected paths and to template-generated files.
int ProtectPaths()
{
    if (relPath is null)
        return 0;

    var globs = File.Exists(Path.Combine(cwd, ".claude/hooks/protected-paths.txt"))
        ? File.ReadAllLines(Path.Combine(cwd, ".claude/hooks/protected-paths.txt")).Where(l => l.Length > 0 && !l.StartsWith('#'))
        : [];
    foreach (var glob in globs)
        if (Regex.IsMatch(relPath, "^" + Regex.Escape(glob.Trim()).Replace(@"\*\*", ".*").Replace(@"\*", "[^/]*") + "$"))
            return Deny($"'{relPath}' is protected ({glob.Trim()}). Changes go through a PR by its CODEOWNERS; see .claude/hooks/protected-paths.txt.");

    var full = Path.Combine(cwd, relPath);
    if (File.Exists(full) && GeneratedMarker.TryRead(File.ReadAllText(full)) is { } marker)
        return Deny($"'{relPath}' is generated by template {marker.TemplateId}@{marker.Version}. Regenerate it with the template tool, " +
                    "or remove its first-line aico:generated marker if a hand-written customization is intended (it will then be reviewed as hand-written).");
    return 0;
}

// PreToolUse(Edit|Write|MultiEdit): keep credentials out of the diff.
int NoSecrets()
{
    var text = string.Join("\n", new[] { "content", "new_string" }.Select(k => toolInput[k]?.GetValue<string>() ?? ""))
        + string.Join("\n", (toolInput["edits"] as JsonArray ?? []).Select(e => e?["new_string"]?.GetValue<string>() ?? ""));
    (string Name, string Pattern)[] rules =
    [
        ("AWS access key", @"AKIA[0-9A-Z]{16}"),
        ("GitHub token", @"gh[pousr]_[A-Za-z0-9]{36,}"),
        ("Anthropic API key", @"sk-ant-[A-Za-z0-9_\-]{20,}"),
        ("private key", @"-----BEGIN (RSA |EC |OPENSSH |)PRIVATE KEY-----"),
        ("connection string password", @"(?i)(password|pwd)\s*=\s*[^;\s""']{6,}"),
        ("Azure storage key", @"AccountKey=[A-Za-z0-9+/=]{40,}"),
    ];
    foreach (var (name, pattern) in rules)
        if (Regex.IsMatch(text, pattern))
            return Deny($"Possible {name} in '{relPath}'. Use user-secrets, environment variables or Key Vault; never commit credentials.");
    return 0;
}

// PreToolUse(Edit|Write|MultiEdit): keep implementation inside the approved plan.md (opt-in via .aico/active-plan).
int PlanScope()
{
    var marker = Path.Combine(cwd, ".aico", "active-plan");
    if (relPath is null || !File.Exists(marker))
        return 0;
    var planPath = Path.Combine(cwd, File.ReadAllText(marker).Trim());
    if (!File.Exists(planPath))
        return 0;

    var plan = File.ReadAllText(planPath);
    var named = Regex.Matches(plan, @"`([^`\s]+\.[A-Za-z0-9]+)`").Select(m => m.Groups[1].Value.TrimStart('.', '/')).ToHashSet();
    if (named.Any(n => relPath.EndsWith(n, StringComparison.OrdinalIgnoreCase)))
        return 0;
    return Emit("PreToolUse", new JsonObject
    {
        ["permissionDecision"] = "ask",
        ["permissionDecisionReason"] = $"'{relPath}' is not named in the approved plan ({File.ReadAllText(marker).Trim()}). Approve if this is in scope, or update plan.md first.",
    });
}

// PostToolUse(Edit|Write|MultiEdit): format the touched C# file. Never blocks.
int Format()
{
    if (relPath is null || !relPath.EndsWith(".cs", StringComparison.OrdinalIgnoreCase))
        return 0;
    using var p = Process.Start(new ProcessStartInfo("dotnet", ["format", "whitespace", ".", "--folder", "--include", relPath])
    {
        WorkingDirectory = cwd,
        RedirectStandardOutput = true,
        RedirectStandardError = true,
    });
    p?.WaitForExit(TimeSpan.FromSeconds(30));
    return 0;
}

static int Emit(string eventName, JsonObject output)
{
    output["hookEventName"] = eventName;
    Console.WriteLine(new JsonObject { ["hookSpecificOutput"] = output }.ToJsonString());
    return 0;
}

static int Deny(string reason) => Emit("PreToolUse", new JsonObject
{
    ["permissionDecision"] = "deny",
    ["permissionDecisionReason"] = reason,
});

static int Fail(string message)
{
    Console.Error.WriteLine(message);
    return 1;
}
